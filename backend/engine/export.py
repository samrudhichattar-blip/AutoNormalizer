"""
Export the normalized database: one CSV per table + schema.sql (CREATE TABLE, INSERT rows, then foreign keys) in a ZIP.

Foreign keys are added AFTER the rows are inserted, so load order never matters. If the data itself contradicts a primary key
(for example the same CustomerID with two different names), nothing is exported and the conflicting rows are shown instead.
"""
import csv
import io
import zipfile
from collections import defaultdict

from backend.engine.er_diagram import check_dialect, fk_statement, literal, quote, table_order, to_ddl


def project_tables(rows, er):
    """{table: (columns, distinct tuples in first-seen order)}"""
    out = {}
    for e in er["entities"]:
        cols = [a["name"] for a in e["attributes"]]
        out[e["name"]] = (cols, list(dict.fromkeys(tuple(r[c] for c in cols) for r in rows)))
    return out


def primary_key_conflicts(er, tables, sample=3):
    found = []
    for e in er["entities"]:
        cols, tuples = tables[e["name"]]
        idx = [cols.index(c) for c in e["primary_key"]]
        groups = defaultdict(list)
        for t in tuples: groups[tuple(t[i] for i in idx)].append(t)
        bad = [(k, v) for k, v in groups.items() if len(v) > 1]
        if bad:
            found.append({"table": e["name"], "primary_key": e["primary_key"], "conflicting_keys": len(bad),
                          "examples": [{"key": dict(zip(e["primary_key"], k)), "variants": [dict(zip(cols, t)) for t in v]} for k, v in bad[:sample]]})
    return found


def schema_sql(er, tables, types, dialect):
    dialect = check_dialect(dialect); q = lambda s: quote(s, dialect)
    ents = {e["name"]: e for e in er["entities"]}
    parts = [f"-- Generated by AutoNormalizer Plus. Dialect: {dialect}\n"]
    ddl = to_ddl(er, dialect).split("\n\n")
    creates = [x for x in ddl if x.startswith("CREATE")]
    parts += creates
    for name in table_order(er):
        cols, tuples = tables[name]
        head = f"INSERT INTO {q(name)} ({', '.join(q(c) for c in cols)}) VALUES "
        parts.append(f"-- {len(tuples)} row(s) for {name}")
        parts += [head + "(" + ", ".join(literal(v, types.get(c, "text"), dialect) for c, v in zip(cols, t)) + ");" for t in tuples]
    if dialect == "oracle": parts.append("COMMIT;")
    parts += [fk_statement(f, n, dialect) for n, f in enumerate(er["relationships"], 1)]
    return "\n".join(parts) + "\n"


def build_zip(er, rows, types, dialect, proof=None):
    tables = project_tables(rows, er)
    conflicts = primary_key_conflicts(er, tables)
    if conflicts: return None, conflicts
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as z:
        for name, (cols, tuples) in tables.items():
            s = io.StringIO(); w = csv.writer(s, lineterminator="\n"); w.writerow(cols); w.writerows(tuples)
            z.writestr(f"tables/{name}.csv", s.getvalue())
        z.writestr("schema.sql", schema_sql(er, tables, types, dialect))
        lines = ["AutoNormalizer Plus export", f"SQL dialect: {dialect}", "", "Tables:"] + [f"  {n}: {len(t)} row(s)" for n, (_, t) in tables.items()]
        if proof and proof.get("lossless") is not None:
            lines += ["", "Reconstruction check on your data: " + ("LOSSLESS, joining the tables gives back all %d original distinct rows." % proof["original_distinct_rows"]
                                                                  if proof["lossless"] else "NOT lossless.")]
        lines += ["", "Run schema.sql on an empty database. Foreign keys are added at the end, after the rows are loaded."]
        z.writestr("README.txt", "\n".join(lines) + "\n")
    return buf.getvalue(), []
